"""
SYNTHETIC STUDENT PERFORMANCE DATASET GENERATOR
------------------------------------------------
Statistical Machine Learning (SML) College Project - Duolingo Adaptive Learning Platform

NOTE: All records generated by this script are synthetic demonstration data created
to model realistic educational cognitive distributions, response latencies, and
mastery transitions without violating privacy or requiring proprietary external data.
"""

import os
import csv
import random
import math

TOPICS = [
    "Spanish Basics",
    "Grammar & Verbs",
    "Food & Dining",
    "Travel & Places",
    "Numbers & Time"
]

MASTERY_LEVELS = ["Beginner", "Intermediate", "Advanced"]

def clip(val, low, high):
    return max(low, min(high, val))

def generate_student_dataset(n_samples: int = 1800, random_state: int = 42):
    random.seed(random_state)
    
    rows = []
    
    for _ in range(n_samples):
        stu_id = f"STU_{random.randint(1001, 1350):04d}"
        topic = random.choices(TOPICS, weights=[0.25, 0.25, 0.20, 0.15, 0.15])[0]
        
        # 3 latent student ability clusters to reflect realistic educational skill
        ability = random.choices(["low", "medium", "high"], weights=[0.30, 0.45, 0.25])[0]
        
        if ability == "low":
            p_acc = clip(random.gauss(0.52, 0.12), 0.15, 0.75)
            t_acc = clip(p_acc + random.gauss(0.0, 0.08), 0.10, 0.80)
            att = int(clip(random.gauss(2.8, 0.8), 1, 5))
            resp = clip(random.gauss(24.0, 5.5), 10.0, 45.0)
            comp = clip(random.betavariate(4, 2), 0.35, 1.0)
            cons = clip(random.betavariate(3, 3), 0.15, 0.85)
            imp = clip(random.gauss(-0.02, 0.08), -0.25, 0.20)
            p_mast = random.choices(["Beginner", "Intermediate"], weights=[0.85, 0.15])[0]
            
            # Ground truth mastery scoring formula with noise
            composite = 0.35 * p_acc + 0.25 * t_acc + 0.15 * (1 - resp / 45.0) + 0.15 * cons + 0.10 * (imp + 0.25)
            if composite > 0.62:
                t_mast = "Intermediate"
            else:
                t_mast = "Beginner"
                
        elif ability == "medium":
            p_acc = clip(random.gauss(0.72, 0.10), 0.45, 0.90)
            t_acc = clip(p_acc + random.gauss(0.0, 0.07), 0.35, 0.95)
            att = int(clip(random.gauss(1.9, 0.6), 1, 4))
            resp = clip(random.gauss(15.5, 4.0), 7.0, 32.0)
            comp = clip(random.betavariate(6, 2), 0.50, 1.0)
            cons = clip(random.betavariate(5, 3), 0.30, 0.95)
            imp = clip(random.gauss(0.05, 0.07), -0.15, 0.25)
            p_mast = random.choices(["Beginner", "Intermediate", "Advanced"], weights=[0.20, 0.70, 0.10])[0]
            
            composite = 0.35 * p_acc + 0.25 * t_acc + 0.15 * (1 - resp / 45.0) + 0.15 * cons + 0.10 * (imp + 0.25)
            if composite > 0.76:
                t_mast = "Advanced"
            elif composite < 0.52:
                t_mast = "Beginner"
            else:
                t_mast = "Intermediate"
                
        else: # high ability
            p_acc = clip(random.gauss(0.88, 0.07), 0.70, 1.0)
            t_acc = clip(p_acc + random.gauss(0.0, 0.05), 0.65, 1.0)
            att = int(clip(random.gauss(1.2, 0.4), 1, 2))
            resp = clip(random.gauss(8.5, 2.5), 3.5, 20.0)
            comp = clip(random.betavariate(8, 1.5), 0.75, 1.0)
            cons = clip(random.betavariate(8, 2), 0.60, 1.0)
            imp = clip(random.gauss(0.09, 0.06), -0.05, 0.30)
            p_mast = random.choices(["Intermediate", "Advanced"], weights=[0.20, 0.80])[0]
            
            composite = 0.35 * p_acc + 0.25 * t_acc + 0.15 * (1 - resp / 45.0) + 0.15 * cons + 0.10 * (imp + 0.25)
            if composite < 0.68:
                t_mast = "Intermediate"
            else:
                t_mast = "Advanced"
        
        # Inject ~2% cognitive noise (fatigue, lucky guesses) to simulate real-world classroom variance
        if random.random() < 0.02:
            t_mast = random.choice(MASTERY_LEVELS)
            
        rows.append({
            "student_id": stu_id,
            "topic": topic,
            "previous_accuracy": round(p_acc, 4),
            "topic_accuracy": round(t_acc, 4),
            "num_attempts": att,
            "avg_response_time": round(resp, 2),
            "completion_rate": round(comp, 4),
            "learning_consistency": round(cons, 4),
            "recent_improvement": round(imp, 4),
            "previous_mastery": p_mast,
            "target_mastery": t_mast
        })
        
    return rows

def save_dataset(output_path: str = None):
    if output_path is None:
        base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        output_path = os.path.join(base_dir, "data", "student_performance.csv")
        
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    rows = generate_student_dataset(n_samples=1800, random_state=42)
    
    fieldnames = [
        "student_id",
        "topic",
        "previous_accuracy",
        "topic_accuracy",
        "num_attempts",
        "avg_response_time",
        "completion_rate",
        "learning_consistency",
        "recent_improvement",
        "previous_mastery",
        "target_mastery"
    ]
    
    with open(output_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
        
    print(f"[OK] Synthetic student performance dataset generated successfully ({len(rows)} records): {output_path}")

if __name__ == "__main__":
    save_dataset()
